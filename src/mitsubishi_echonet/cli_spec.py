"""Canonical definition of the shipped mitsubishi-echonet command line (issue #54).

Single source of truth feeding both:

- the short explanations printed by ``--help`` (``cli.build_parser`` imports
  these strings when it builds its argparse parsers), and
- the Linux man pages generated by ``tools/build_man_pages.py`` into
  ``man/man1/`` and installed by ``tools/install_man_pages.sh``.

``tests/test_cli_docs.py`` proves the shipped ``--help`` output and the
committed man pages never drift from this file. Edit command text here only.

Only the shipped console script belongs here; internal development and CI
scripts (scripts/, docker entrypoint) are deliberately not part of this
command surface. No real adapter IPs or network details: invented examples
only.
"""

from __future__ import annotations

from typing import NamedTuple

PROGRAM = "mitsubishi-echonet"
MANUAL = "Mitsubishi ECHONET Manual"
MAN_DATE = "November 2026"

PROGRAM_DESCRIPTION = (
    "Enable, disable and verify local ECHONET Lite control on Mitsubishi "
    "Electric MAC-577IF-E-class Wi-Fi adapters. Run only on a trusted "
    "network: ECHONET Lite has no authentication."
)

TRUST_WARNING = (
    "ECHONET Lite has no authentication: any host on the local network can "
    "send these commands. Run only on a trusted network."
)


class Opt(NamedTuple):
    """One command-line option. required means the command refuses to run
    without it. metavar None means the option takes no value."""

    flag: str
    metavar: str | None
    help: str
    required: bool = False
    default: str | None = None


class Command(NamedTuple):
    """One shipped subcommand."""

    name: str
    summary: str
    description: tuple[str, ...]
    options: tuple[Opt, ...]
    examples: tuple[tuple[str, str], ...] = ()


_IP = Opt("--ip", "IP", "adapter IP address on the local network", required=True)
_TIMEOUT = Opt("--timeout", "SECONDS", "seconds to wait", default="3")

COMMANDS: dict[str, Command] = {
    c.name: c
    for c in (
        Command(
            "enable",
            "enable ECHONET Lite via the /smart endpoint",
            ("Sends the enable command to the adapter's /smart endpoint. " + TRUST_WARNING,),
            (_IP, _TIMEOUT),
            (
                (
                    "mitsubishi-echonet enable --ip 192.0.2.10",
                    "Enable ECHONET Lite on the adapter at 192.0.2.10 (documentation IP).",
                ),
            ),
        ),
        Command(
            "disable",
            "disable ECHONET Lite via the /smart endpoint",
            ("Sends the disable command to the adapter's /smart endpoint. " + TRUST_WARNING,),
            (_IP, _TIMEOUT),
            (
                (
                    "mitsubishi-echonet disable --ip 192.0.2.10",
                    "Disable ECHONET Lite on the adapter at 192.0.2.10.",
                ),
            ),
        ),
        Command(
            "status",
            "read-only check: is the adapter reachable and is ECHONET Lite on?",
            (
                "Read-only. Reports whether the adapter answers and whether ECHONET "
                "Lite control is currently enabled.",
            ),
            (_IP, _TIMEOUT),
            (("mitsubishi-echonet status --ip 192.0.2.10", "Check the adapter at 192.0.2.10."),),
        ),
        Command(
            "capabilities",
            "read-only: list the adapter's supported ECHONET properties (incl. timers)",
            (
                "Read-only. Lists the ECHONET properties the adapter supports, "
                "including timer support.",
            ),
            (_IP, _TIMEOUT),
            (
                (
                    "mitsubishi-echonet capabilities --ip 192.0.2.10",
                    "List supported properties of the adapter at 192.0.2.10.",
                ),
            ),
        ),
        Command(
            "discover",
            "multicast discovery of ECHONET Lite devices",
            (
                "Sends a multicast discovery and prints every ECHONET Lite device "
                "that answers within the timeout. Exits 1 when no device answers.",
            ),
            (Opt("--timeout", "SECONDS", "seconds to listen", default="3"),),
            (
                (
                    "mitsubishi-echonet discover",
                    "Discover ECHONET Lite devices on the local network.",
                ),
            ),
        ),
    )
}

VERSION_OPT = Opt("--version", None, "print the version and exit")
